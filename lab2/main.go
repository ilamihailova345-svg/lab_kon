package main

import (
	"flag"
	"fmt"
	"time"
)

func main() {
	// Используем флаги для запуска:
	// go run main.go -n 10 -m 3
	// -n это количество горутин, а -m это количество сообщений от каждой
	n := flag.Int("n", 5, "количество горутин")
	m := flag.Int("m", 3, "количество сообщений от каждой горутины")
	flag.Parse()

	fmt.Printf("Запуск %d горутин, каждая напечатает %d сообщений\n", *n, *m)

	// Запускаем n горутин
	for i := 1; i <= *n; i++ {
		// передаем i как аргумент, чтобы избежать проблемы замыкания
		go func(id int) {
			for j := 1; j <= *m; j++ {
				fmt.Printf("[goroutine %d] message %d\n", id, j)
				// пауза, чтобы вывод перемешивался и было видно, что они работают параллельно
				time.Sleep(50 * time.Millisecond)
			}
		}(i)
	}

	// НЕНАДЕЖНО:
	// Не знаем, сколько времени реально нужно горутинам на работу
	// Если компьютер загружен (или горутин слишком много), им потребуется больше времени
	// time.Sleep - это просто фиксированная пауза, мы гадаем, а не ждем
	// Если горутины не успеют, программа завершится

	// Ждем с запасом
	time.Sleep(2 * time.Second)
	fmt.Println("Программа завершена")
}
